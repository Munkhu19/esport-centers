class EsportCenter {
  final String id;
  final String name;
  final String address;
  final int pcCount;
  final String pcSpec;
  final int price;
  final String phone;
  final double latitude;
  final double longitude;

  EsportCenter({
    required this.id,
    required this.name,
    required this.address,
    required this.pcCount,
    required this.pcSpec,
    required this.price,
    required this.phone,
    required this.latitude,
    required this.longitude,
  });
}
